#!/usr/bin/env python3
"""Generate faro's emoji table from Unicode's data (D103).

    python3 tools/emoji/gen_table.py [--cache DIR]

Downloads (or reads from --cache) two pinned files:
  - emoji-test.txt (Unicode Emoji 18.0): the emoji, in Unicode's order,
    with the Emoji version each was added in;
  - CLDR 48.2.3 English annotations (cldr-json): each emoji's official
    name and search keywords (annotations.json, plus annotationsDerived for
    sequences such as people with professions).

and writes crates/faro-app/src/ui/shortcodes/table.rs: every fully-qualified emoji
up to MAX_VERSION, without skin-tone variants, with its name and keywords.
Both files are under the Unicode License v3 (THIRD_PARTY_NOTICES.md).
Re-run after changing a version below; the result is committed.
"""

import argparse
import json
import os
import re
import sys
import unicodedata
import urllib.request

EMOJI_VERSION = "18.0"
CLDR_VERSION = "48.2.3"
# Newest Emoji version included: every part of the chain (tmux 3.6b,
# unicode-width, glibc's wcwidth for mosh, common emoji fonts) knows it.
MAX_VERSION = 16.0

SOURCES = {
    "emoji-test.txt": f"https://www.unicode.org/Public/emoji/{EMOJI_VERSION}/emoji-test.txt",
    "annotations.json": (
        "https://raw.githubusercontent.com/unicode-org/cldr-json/"
        f"{CLDR_VERSION}/cldr-json/cldr-annotations-full/annotations/en/annotations.json"
    ),
    "derived.json": (
        "https://raw.githubusercontent.com/unicode-org/cldr-json/"
        f"{CLDR_VERSION}/cldr-json/cldr-annotations-derived-full/annotationsDerived/en/annotations.json"
    ),
}

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "crates/faro-app/src/ui/shortcodes/table.rs")
SKIN_TONES = range(0x1F3FB, 0x1F400)
LINE = re.compile(r"^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E(\d+\.\d+) (.*)$")


def fetch(name, cache):
    if cache:
        path = os.path.join(cache, name)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                return f.read()
    with urllib.request.urlopen(SOURCES[name]) as response:
        text = response.read().decode("utf-8")
    if cache:
        os.makedirs(cache, exist_ok=True)
        with open(os.path.join(cache, name), "w", encoding="utf-8") as f:
            f.write(text)
    return text


def code_of(name):
    """A name as a `:shortcode:`: lowercase ASCII words joined by `_`
    ("flag: Côte d’Ivoire" -> "flag_cote_divoire", "keycap: #" -> "keycap_hash")."""
    name = name.replace("#", " hash ").replace("*", " asterisk ").replace("’", "").replace("'", "")
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return "_".join(re.findall(r"[a-z0-9+-]+", ascii_name.lower()))


def rust_str(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", help="directory to keep the downloaded files in")
    args = ap.parse_args()

    tests = fetch("emoji-test.txt", args.cache)
    annotations = json.loads(fetch("annotations.json", args.cache))["annotations"]["annotations"]
    derived = json.loads(fetch("derived.json", args.cache))["annotationsDerived"]["annotations"]

    def lookup(emoji):
        for key in (emoji, emoji.replace("\ufe0f", "")):
            for table in (annotations, derived):
                if key in table:
                    return table[key]
        return None

    rows = []
    skipped_new = 0
    for line in tests.splitlines():
        m = LINE.match(line)
        if not m:
            continue
        code_points = [int(cp, 16) for cp in m.group(1).split()]
        if any(cp in SKIN_TONES for cp in code_points):
            continue
        emoji, version, fallback = m.group(2), float(m.group(3)), m.group(4)
        if version > MAX_VERSION:
            skipped_new += 1
            continue
        found = lookup(emoji)
        if found is None:
            sys.exit(f"no CLDR annotation for {emoji} ({fallback})")
        name = found.get("tts", [fallback])[0]
        keywords = []
        for keyword in found.get("default", []):
            keyword = keyword.lower().strip()
            if keyword and keyword not in keywords and "|" not in keyword:
                keywords.append(keyword)
        code = code_of(name)
        taken = {row[1] for row in rows}
        if code in taken:
            n = 2
            while f"{code}_{n}" in taken:
                n += 1
            code = f"{code}_{n}"
        rows.append((emoji, code, "|".join(keywords)))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(
            "//! Generated by `tools/emoji/gen_table.py` (D103): do not edit.\n"
            f"//! Unicode Emoji {EMOJI_VERSION} (up to Emoji {MAX_VERSION}, no skin-tone variants),\n"
            f"//! names and keywords from CLDR {CLDR_VERSION}; Unicode License v3.\n\n"
            "/// Every emoji, in Unicode's order: the emoji, its `:shortcode:` (its CLDR\n"
            "/// name in lowercase ASCII words joined by `_`, unique), and its CLDR\n"
            "/// keywords (lowercase, `|`-separated).\n"
            "#[rustfmt::skip]\n"
            "pub(super) const EMOJI: &[(&str, &str, &str)] = &[\n"
        )
        for emoji, code, keywords in rows:
            f.write(f"    ({rust_str(emoji)}, {rust_str(code)}, {rust_str(keywords)}),\n")
        f.write("];\n")
    print(f"{len(rows)} emoji written to {os.path.relpath(OUT, REPO)}; {skipped_new} newer than Emoji {MAX_VERSION} left out")


if __name__ == "__main__":
    main()
